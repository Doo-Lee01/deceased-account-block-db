-- =====================================================================
-- 01_deadlock.sql  —  시나리오 1 : 데드락이 걸리는 경우
--
-- 무엇을 보여주나
--   README 3장 "거래 한 건의 처리" 순서 그대로
--     ① 거래원장(acct_txn)에 기록  →  ② 계좌(acct) 잔액 변경
--   을 두 사람이 같은 계좌에 동시에 하면 데드락이 난다.
--
-- 왜 걸리나 (한 줄 요약)
--   ①에서 FK 확인 때문에 계좌 행에 "읽는 중(S)" 락이 자동으로 붙는다.
--   A · B 둘 다 S 를 쥔 채로 ②에서 "고치는 중(X)" 을 요청하면,
--   서로 상대의 S 가 풀리길 기다리며 영원히 멈춘다.
--
-- 사용 터미널 : A · B · OBS
-- 진행 방법   : [STEP n] ▶ 터미널이름 표시대로, 해당 블록을 그 터미널에
--               복사해 붙여넣는다. 반드시 번호 순서대로.
--
-- 결과 요약
--   · STEP 5 에서 A 가 멈춘다
--   · STEP 7 에서 B 가 ERROR 1213 으로 취소되고, 그 순간 A 가 풀린다
--   · 최종 잔액 1,010,000 — A 의 입금만 반영
-- =====================================================================


-- ─────────────────────────────────────────────────────────────────────
-- [STEP 0] ▶ OBS  —  시연 계좌를 처음 상태로
-- ─────────────────────────────────────────────────────────────────────
CALL lock_lab.reset();
-- 기대: 초기화 완료 — 시연 계좌 잔액 1,000,000원


-- ─────────────────────────────────────────────────────────────────────
-- [STEP 1] ▶ A  —  트랜잭션 시작, 잔액 읽기, 원장 기록
-- ─────────────────────────────────────────────────────────────────────
BEGIN;                                     -- 여기부터 COMMIT 까지가 한 묶음

SELECT balance_amt INTO @bal               -- 잔액을 변수 @bal 에 담는다
  FROM acct
 WHERE acct_no = '10288000000001';         -- 락을 걸지 않는 평범한 읽기
SELECT @bal AS read_balance;               -- 기대: 1000000.00

INSERT INTO acct_txn                       -- ① 거래원장에 입금 1만원 기록
  (txn_unique_no, acct_no, txn_dtm, txn_type_cd, dr_cr_cd,
   txn_amt, balance_after_amt, chnl_cd, rsp_cd)
VALUES
  ('DEMO-S1-A', '10288000000001', NOW(3), 'DEP', 'I',
   10000, @bal + 10000, '10', '0000');
-- 기대: Query OK, 1 row affected
--
-- ★ 이 INSERT 가 숨은 일을 한다
--   acct_txn.acct_no 에는 FK(fk_txn_acct)가 걸려 있다.
--   MySQL 은 "그 계좌가 정말 있나?" 를 확인하면서, 기록이 끝날 때까지
--   계좌가 지워지지 않도록 계좌 행에 S 락(읽는 중)을 붙인다.
--   이 S 락은 COMMIT 할 때까지 풀리지 않는다.


-- ─────────────────────────────────────────────────────────────────────
-- [STEP 2] ▶ OBS  —  계좌 행에 누가 무슨 락을 쥐고 있나
-- ─────────────────────────────────────────────────────────────────────
SELECT who, tbl, kind, raw_mode, status, row_key FROM lock_lab.v_locks;
-- 기대:
-- | who | tbl  | kind     | raw_mode      | status  | row_key          |
-- | A   | acct | S (read) | S,REC_NOT_GAP | GRANTED | '10288000000001' |
--
-- raw_mode 읽는 법
--   S            = 공유락(읽는 중). 여러 세션이 동시에 가질 수 있다
--   REC_NOT_GAP  = 행 하나만 잠금 (행 사이 빈 공간은 잠그지 않음)
--   GRANTED      = 이미 쥐고 있음


-- ─────────────────────────────────────────────────────────────────────
-- [STEP 3] ▶ B  —  B 도 똑같이 원장 기록
-- ─────────────────────────────────────────────────────────────────────
BEGIN;
SELECT balance_amt INTO @bal FROM acct WHERE acct_no = '10288000000001';
SELECT @bal AS read_balance;               -- 기대: 1000000.00  (A 는 아직 커밋 전)

INSERT INTO acct_txn
  (txn_unique_no, acct_no, txn_dtm, txn_type_cd, dr_cr_cd,
   txn_amt, balance_after_amt, chnl_cd, rsp_cd)
VALUES
  ('DEMO-S1-B', '10288000000001', NOW(3), 'DEP', 'I',
   10000, @bal + 10000, '10', '0000');
-- 기대: Query OK — 멈추지 않는다.
--       S 락끼리는 함께 가질 수 있으므로 B 도 바로 통과한다.
--
-- 참고: B 가 기록한 거래후잔액도 1,010,000 이다. A 가 먼저 입금했으니
--       실제로는 1,020,000 이어야 한다. 잠그지 않고 읽은 값으로 계산하면
--       이런 오류도 함께 생긴다.


-- ─────────────────────────────────────────────────────────────────────
-- [STEP 4] ▶ OBS  —  같은 행에 S 락이 두 개
-- ─────────────────────────────────────────────────────────────────────
SELECT who, tbl, kind, raw_mode, status, row_key FROM lock_lab.v_locks;
-- 기대:
-- | who | kind     | raw_mode      | status  |
-- | A   | S (read) | S,REC_NOT_GAP | GRANTED |
-- | B   | S (read) | S,REC_NOT_GAP | GRANTED |
--
-- 여기가 데드락의 씨앗이다. 둘 다 "읽는 중" 표시를 쥔 채로
-- 곧 "고치는 중" 으로 바꾸려 할 것이다.


-- ─────────────────────────────────────────────────────────────────────
-- [STEP 5] ▶ A  —  ② 잔액 변경  →  멈춘다
-- ─────────────────────────────────────────────────────────────────────
UPDATE acct
   SET balance_amt = balance_amt + 10000
 WHERE acct_no = '10288000000001';
-- 기대: 아무 출력 없이 멈춤 (커서만 깜빡인다)
--
-- 왜 멈추나
--   잔액을 바꾸려면 X 락(고치는 중)이 필요하다.
--   그런데 B 가 같은 행에 S 락을 쥐고 있다.
--   "누가 읽고 있으면 고칠 수 없다" 는 규칙 때문에 A 는 기다린다.


-- ─────────────────────────────────────────────────────────────────────
-- [STEP 6] ▶ OBS  —  누가 누구를 기다리나
-- ─────────────────────────────────────────────────────────────────────
SELECT * FROM lock_lab.v_waits;
-- 기대:
-- | waiting | wants         | blocked_by | holds         |
-- | A       | X,REC_NOT_GAP | B          | S,REC_NOT_GAP |
-- → A 가 X 를 원하는데, B 가 S 를 쥐고 있어서 못 받는 중

SELECT who, state, rows_locked, running_sql FROM lock_lab.v_trx;
-- 기대:
-- | who | state     | running_sql          |
-- | A   | LOCK WAIT | UPDATE acct SET ...  |
-- | B   | RUNNING   | NULL                 |


-- ─────────────────────────────────────────────────────────────────────
-- [STEP 7] ▶ B  —  B 도 잔액 변경  →  데드락
-- ─────────────────────────────────────────────────────────────────────
UPDATE acct
   SET balance_amt = balance_amt + 10000
 WHERE acct_no = '10288000000001';
-- 기대 (B 화면):
--   ERROR 1213 (40001): Deadlock found when trying to get lock;
--   try restarting transaction
-- 기대 (A 화면): 그 순간 STEP 5 의 멈춤이 풀리며
--   Query OK, 1 row affected
--
-- 무슨 일이 일어났나
--   B 도 X 락을 요청했는데 A 가 S 락을 쥐고 있다.
--   A 는 B 를, B 는 A 를 기다리는 원형 대기가 완성됐다.
--   MySQL 은 이걸 즉시 감지하고 한쪽(여기서는 B)을 통째로 취소한다.
--   B 의 INSERT 도 함께 사라지고, B 가 쥐었던 S 락도 풀려서 A 가 진행된다.


-- ─────────────────────────────────────────────────────────────────────
-- [STEP 8] ▶ A 에서 COMMIT,  ▶ B 에서 ROLLBACK
-- ─────────────────────────────────────────────────────────────────────
-- ▶ A
COMMIT;
-- ▶ B  (이미 취소됐지만 트랜잭션 상태를 깨끗이 정리)
ROLLBACK;


-- ─────────────────────────────────────────────────────────────────────
-- [STEP 9] ▶ OBS  —  결과
-- ─────────────────────────────────────────────────────────────────────
SELECT * FROM lock_lab.v_acct;
-- 기대:
-- | item      | value     | note            |
-- | BALANCE   | 1,010,000 | NULL            |
-- | DEMO-S1-A | +10,000   | after 1,010,000 |
-- → 두 사람이 입금했는데 한 건만 반영. B 는 "입금 실패" 를 받았다.


-- ─────────────────────────────────────────────────────────────────────
-- [STEP 10] ▶ OBS  —  MySQL 이 남긴 데드락 기록
-- ─────────────────────────────────────────────────────────────────────
SHOW ENGINE INNODB STATUS\G
-- 긴 출력 중 "LATEST DETECTED DEADLOCK" 부분을 찾는다.
--
--   *** (1) TRANSACTION:            ← A
--   UPDATE acct SET balance_amt = balance_amt + 10000 ...
--   *** (1) HOLDS THE LOCK(S):
--   ... lock mode S locks rec but not gap      ← A 는 S 를 쥐고
--   *** (1) WAITING FOR THIS LOCK TO BE GRANTED:
--   ... lock_mode X locks rec but not gap      ← X 를 기다림
--
--   *** (2) TRANSACTION:            ← B
--   (같은 모양)
--
--   *** WE ROLL BACK TRANSACTION (2)          ← B 를 취소함
