-- =====================================================================
-- 02_deadlock_fixed.sql  —  시나리오 2 : 데드락이 걸리지 않는 경우
--
-- 무엇을 바꿨나
--   시작하자마자 계좌 행을 SELECT ... FOR UPDATE 로 읽는다.
--   FOR UPDATE 는 "읽기만 하는 게 아니라 곧 고칠 거야" 라는 선언이라
--   처음부터 X 락(고치는 중)을 잡는다.
--
-- 왜 해결되나
--   시나리오 1 은 둘 다 S 를 쥔 채로 X 를 기다려서 꼬였다.
--   이번엔 먼저 온 A 가 X 를 쥐고, 늦게 온 B 는 아무것도 쥐지 못한 채
--   맨 앞에서 기다린다. 서로 붙잡고 기다리는 상황이 생기지 않는다.
--
--   처리 순서 (시나리오 1 과 비교)
--     1번: 읽기 → ① 원장 기록 → ② 잔액 변경          ← 데드락
--     2번: 잠그며 읽기 → ① 원장 기록 → ② 잔액 변경    ← 차례대로 처리
--
-- 사용 터미널 : A · B · OBS
-- 결과 요약
--   · STEP 3 에서 B 가 멈춘다 (하지만 락을 쥐지 않은 채로)
--   · STEP 5 에서 A 가 끝나면 B 가 풀리고, 갱신된 잔액을 본다
--   · 최종 잔액 1,020,000 — 두 입금 모두 반영, 오류 없음
-- =====================================================================


-- ─────────────────────────────────────────────────────────────────────
-- [STEP 0] ▶ OBS
-- ─────────────────────────────────────────────────────────────────────
CALL lock_lab.reset();


-- ─────────────────────────────────────────────────────────────────────
-- [STEP 1] ▶ A  —  잠그면서 읽기
-- ─────────────────────────────────────────────────────────────────────
BEGIN;

SELECT balance_amt INTO @bal
  FROM acct
 WHERE acct_no = '10288000000001'
   FOR UPDATE;                     -- ★ 핵심. 이 한 줄이 X 락을 먼저 잡는다
SELECT @bal AS locked_balance;     -- 기대: 1000000.00


-- ─────────────────────────────────────────────────────────────────────
-- [STEP 2] ▶ OBS
-- ─────────────────────────────────────────────────────────────────────
SELECT who, tbl, kind, raw_mode, status, row_key FROM lock_lab.v_locks;
-- 기대:
-- | who | kind      | raw_mode      | status  |
-- | A   | X (write) | X,REC_NOT_GAP | GRANTED |
-- → 시나리오 1 과 달리 처음부터 X 다.


-- ─────────────────────────────────────────────────────────────────────
-- [STEP 3] ▶ B  —  B 도 잠그면서 읽기  →  멈춘다
-- ─────────────────────────────────────────────────────────────────────
BEGIN;
SELECT balance_amt INTO @bal
  FROM acct
 WHERE acct_no = '10288000000001'
   FOR UPDATE;                     -- A 가 X 를 쥐고 있으니 여기서 대기
SELECT @bal AS locked_balance;     -- 대기가 풀린 뒤에 출력된다
-- 기대: 아무 출력 없이 멈춤


-- ─────────────────────────────────────────────────────────────────────
-- [STEP 4] ▶ OBS  —  B 는 기다리지만 아무것도 쥐고 있지 않다
-- ─────────────────────────────────────────────────────────────────────
SELECT who, tbl, kind, raw_mode, status, row_key FROM lock_lab.v_locks;
-- 기대:
-- | who | kind      | status  |
-- | A   | X (write) | GRANTED |   ← A 만 쥐고 있음
-- | B   | X (write) | WAITING |   ← B 는 쥔 것 없이 대기
--
-- 시나리오 1 STEP 4 와 비교하면 차이가 보인다.
-- 거기선 B 가 S 를 GRANTED 로 쥐고 있었다. 그게 데드락의 원인이었다.

SELECT * FROM lock_lab.v_waits;
-- 기대: B 가 X 를 원하고, A 가 X 를 쥐고 있음 (한 방향 대기)


-- ─────────────────────────────────────────────────────────────────────
-- [STEP 5] ▶ A  —  원장 기록 → 잔액 변경 → 커밋
-- ─────────────────────────────────────────────────────────────────────
INSERT INTO acct_txn
  (txn_unique_no, acct_no, txn_dtm, txn_type_cd, dr_cr_cd,
   txn_amt, balance_after_amt, chnl_cd, rsp_cd)
VALUES
  ('DEMO-S2-A', '10288000000001', NOW(3), 'DEP', 'I',
   10000, @bal + 10000, '10', '0000');
-- 이 INSERT 도 FK 확인으로 계좌 행에 S 를 요청하지만,
-- A 자신이 이미 X 를 쥐고 있으므로 아무 문제 없이 통과한다.

UPDATE acct
   SET balance_amt = balance_amt + 10000
 WHERE acct_no = '10288000000001';

COMMIT;                            -- 여기서 A 의 X 락이 풀린다
-- 기대 (B 화면): 대기가 풀리며
-- | locked_balance |
-- |     1010000.00 |    ← A 가 입금한 뒤의 잔액을 정확히 본다


-- ─────────────────────────────────────────────────────────────────────
-- [STEP 6] ▶ B  —  B 도 이어서 처리
-- ─────────────────────────────────────────────────────────────────────
INSERT INTO acct_txn
  (txn_unique_no, acct_no, txn_dtm, txn_type_cd, dr_cr_cd,
   txn_amt, balance_after_amt, chnl_cd, rsp_cd)
VALUES
  ('DEMO-S2-B', '10288000000001', NOW(3), 'DEP', 'I',
   10000, @bal + 10000, '10', '0000');   -- 1,010,000 + 10,000 = 1,020,000

UPDATE acct
   SET balance_amt = balance_amt + 10000
 WHERE acct_no = '10288000000001';

COMMIT;


-- ─────────────────────────────────────────────────────────────────────
-- [STEP 7] ▶ OBS  —  결과
-- ─────────────────────────────────────────────────────────────────────
SELECT * FROM lock_lab.v_acct;
-- 기대:
-- | item      | value     | note            |
-- | BALANCE   | 1,020,000 | NULL            |
-- | DEMO-S2-A | +10,000   | after 1,010,000 |
-- | DEMO-S2-B | +10,000   | after 1,020,000 |
-- → 두 입금 모두 반영, 거래후잔액도 순서대로 정확하다.
