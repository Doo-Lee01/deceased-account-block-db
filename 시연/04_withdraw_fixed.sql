-- =====================================================================
-- 04_withdraw_fixed.sql  —  시나리오 4 : 출금 문제 해결
--
-- 무엇을 바꿨나
--   잔액을 볼 때부터 FOR UPDATE 로 잠근다.
--   → 판단하는 시점과 빼는 시점 사이에 아무도 끼어들 수 없다.
--
-- 처리 순서
--   BEGIN
--   ① 잔액을 잠그며 읽기 (FOR UPDATE)
--   ② 잔액이 충분한지 판단
--   ③ 충분하면 잔액 차감 → 원장 기록 → COMMIT
--      부족하면 ROLLBACK
--
-- 이 순서는 시나리오 2 의 데드락 해결과 같은 원리이기도 하다.
-- X 락을 먼저 잡으니 원장 INSERT 의 FK 확인(S 락)과 충돌하지 않는다.
--
-- 사용 터미널 : A · B · OBS
-- 결과 요약
--   · B 는 A 가 끝날 때까지 "잔액을 읽는 것 자체" 를 기다린다
--   · B 는 A 가 빼고 난 30만원을 보고 정상적으로 거절한다
--   · 최종 잔액 300,000, 출금 1건 — 올바른 결과
-- =====================================================================


-- [STEP 0] ▶ OBS
CALL lock_lab.reset();


-- ─────────────────────────────────────────────────────────────────────
-- [STEP 1] ▶ A  —  잠그며 읽기
-- ─────────────────────────────────────────────────────────────────────
BEGIN;
SELECT balance_amt INTO @bal
  FROM acct
 WHERE acct_no = '10288000000001'
   FOR UPDATE;                         -- ★ 보는 순간 잠근다
SELECT @bal AS locked_balance;         -- 기대: 1000000.00


-- ─────────────────────────────────────────────────────────────────────
-- [STEP 2] ▶ B  —  B 도 잠그며 읽기  →  멈춘다
-- ─────────────────────────────────────────────────────────────────────
BEGIN;
SELECT balance_amt INTO @bal
  FROM acct
 WHERE acct_no = '10288000000001'
   FOR UPDATE;
SELECT @bal AS locked_balance;         -- 대기가 풀린 뒤에 출력된다
-- 기대: 아무 출력 없이 멈춤
--   시나리오 3 과의 차이 — 거기선 B 가 바로 100만을 읽었다.
--   이번엔 읽는 것 자체를 기다린다. 낡은 값을 볼 기회가 없다.


-- ─────────────────────────────────────────────────────────────────────
-- [STEP 3] ▶ OBS  —  (선택) 대기 확인
-- ─────────────────────────────────────────────────────────────────────
SELECT * FROM lock_lab.v_waits;
-- 기대: waiting=B, blocked_by=A


-- ─────────────────────────────────────────────────────────────────────
-- [STEP 4] ▶ A  —  판단 → 차감 → 기록 → 커밋
-- ─────────────────────────────────────────────────────────────────────
SELECT IF(@bal >= 700000, '승인', '거절 - 잔액 부족') AS decision;
-- 기대: 승인

UPDATE acct
   SET balance_amt = balance_amt - 700000
 WHERE acct_no = '10288000000001';

INSERT INTO acct_txn
  (txn_unique_no, acct_no, txn_dtm, txn_type_cd, dr_cr_cd,
   txn_amt, balance_after_amt, chnl_cd, rsp_cd)
VALUES
  ('DEMO-S4-A', '10288000000001', NOW(3), 'WDR', 'O',
   700000, @bal - 700000, '20', '0000');

COMMIT;
-- 기대 (B 화면): 대기가 풀리며
-- | locked_balance |
-- |      300000.00 |    ← A 가 빼고 난 진짜 잔액


-- ─────────────────────────────────────────────────────────────────────
-- [STEP 5] ▶ B  —  판단 → 거절
-- ─────────────────────────────────────────────────────────────────────
SELECT IF(@bal >= 700000, '승인', '거절 - 잔액 부족') AS decision;
-- 기대: 거절 - 잔액 부족

ROLLBACK;                              -- 아무것도 바꾸지 않고 락만 푼다


-- ─────────────────────────────────────────────────────────────────────
-- [STEP 6] ▶ OBS  —  결과
-- ─────────────────────────────────────────────────────────────────────
SELECT * FROM lock_lab.v_acct;
-- 기대:
-- | item      | value    | note          |
-- | BALANCE   | 300,000  | NULL          |
-- | DEMO-S4-A | -700,000 | after 300,000 |
-- → 한 명 승인, 한 명 거절. 잔액과 원장이 일치한다.
