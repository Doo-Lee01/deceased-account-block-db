-- =====================================================================
-- 05_read_while_locked.sql  —  시나리오 5 : 잠겨 있어도 조회는 된다
--
-- 이런 질문에 답하는 시나리오
--   "FOR UPDATE 로 잠그면, 조회만 하려는 사람도 못 보게 되는 거 아닌가?"
--
-- 답
--   아니다. 일반 SELECT 는 락을 요청하지 않는다.
--   InnoDB 는 행을 바꿀 때 바뀌기 전 값을 따로 보관해 두고(undo),
--   일반 SELECT 에게는 그 보관본에서 "마지막으로 커밋된 값" 을 꺼내 준다.
--   그래서 누가 X 락을 쥐고 있어도 기다리지 않고 바로 결과가 나온다.
--   이 방식을 MVCC(다중 버전 동시성 제어) 라고 부른다.
--
--   기다리는 것은 "나도 락을 걸겠다" 고 선언한 문장뿐이다.
--
--   | 문장                   | 락 요청 | 남이 X 락 중일 때       |
--   |------------------------|---------|--------------------------|
--   | SELECT                 | 없음    | 바로 나옴 · 커밋된 값   |
--   | SELECT ... FOR SHARE   | S       | 기다림                   |
--   | SELECT ... FOR UPDATE  | X       | 기다림                   |
--   | UPDATE / DELETE        | X       | 기다림                   |
--
-- 조회만 할지, 조회 후 변경할지는 DB 가 알아내는 것이 아니다.
-- 개발자가 어떤 문장을 쓰느냐로 선언한다.
--   · 잔액 조회 화면   → SELECT
--   · 출금 처리        → SELECT ... FOR UPDATE
--
-- 사용 터미널 : A · B · OBS
--   A = 출금 처리 중인 창구
--   B = 모바일 앱에서 잔액을 조회하는 고객
--
-- 결과 요약
--   PART A · A 가 X 락을 쥐고 잔액을 바꾸는 중에도 B 의 일반 SELECT 는 즉시 1,000,000
--          · B 가 FOR SHARE 로 조회하면 A 가 끝날 때까지 기다림
--   PART B · (선택) 한 트랜잭션 안에서는 일반 SELECT 가 계속 같은 값을 본다
-- =====================================================================


-- #####################################################################
-- PART A  —  일반 조회는 기다리지 않는다
-- #####################################################################

-- ─────────────────────────────────────────────────────────────────────
-- [STEP A0] ▶ OBS
-- ─────────────────────────────────────────────────────────────────────
CALL lock_lab.reset();


-- ─────────────────────────────────────────────────────────────────────
-- [STEP A1] ▶ A  —  출금 처리 중 (커밋하지 않고 멈춰 둔다)
-- ─────────────────────────────────────────────────────────────────────
BEGIN;
SELECT balance_amt INTO @bal
  FROM acct
 WHERE acct_no = '10288000000001'
   FOR UPDATE;                               -- X 락
UPDATE acct
   SET balance_amt = balance_amt - 700000    -- 잔액을 30만으로 바꿈
 WHERE acct_no = '10288000000001';
-- 기대: Query OK
-- 아직 COMMIT 하지 않았다. A 는 X 락을 쥔 채로 있다.


-- ─────────────────────────────────────────────────────────────────────
-- [STEP A2] ▶ OBS  —  A 가 X 락을 쥐고 있는지 확인
-- ─────────────────────────────────────────────────────────────────────
SELECT who, tbl, kind, raw_mode, status, row_key FROM lock_lab.v_locks;
-- 기대:
-- | who | kind      | status  |
-- | A   | X (write) | GRANTED |


-- ─────────────────────────────────────────────────────────────────────
-- [STEP A3] ▶ B  —  잔액 조회 (일반 SELECT)
-- ─────────────────────────────────────────────────────────────────────
SELECT balance_amt AS plain_select
  FROM acct
 WHERE acct_no = '10288000000001';
-- 기대: 즉시
-- | plain_select |
-- |   1000000.00 |
--
-- ★ 기다리지 않았다.
--   A 가 X 락을 쥐고 있지만 일반 SELECT 는 락을 요청하지 않기 때문이다.
-- ★ 1,000,000 이 나왔다. A 가 바꾼 30만이 아니다.
--   A 는 아직 커밋하지 않았으므로 확정된 값은 여전히 100만이다.
--   A 가 도중에 ROLLBACK 할 수도 있으니, 확정되지 않은 값을 보여주지 않는다.


-- ─────────────────────────────────────────────────────────────────────
-- [STEP A4] ▶ B  —  이번엔 FOR SHARE 로 조회  →  멈춘다
-- ─────────────────────────────────────────────────────────────────────
BEGIN;
SELECT balance_amt AS for_share
  FROM acct
 WHERE acct_no = '10288000000001'
   FOR SHARE;                                -- "읽는 동안 아무도 못 바꾸게" 하는 S 락 요청
-- 기대: 아무 출력 없이 멈춤
--
-- FOR SHARE 는 S 락을 요청한다.
-- S 와 X 는 함께 존재할 수 없으므로 A 의 X 가 풀릴 때까지 기다린다.


-- ─────────────────────────────────────────────────────────────────────
-- [STEP A5] ▶ OBS  —  B 가 S 락을 기다리는 모습
-- ─────────────────────────────────────────────────────────────────────
SELECT who, tbl, kind, raw_mode, status, row_key FROM lock_lab.v_locks;
-- 기대:
-- | who | kind      | status  |
-- | A   | X (write) | GRANTED |
-- | B   | S (read)  | WAITING |

SELECT * FROM lock_lab.v_waits;
-- 기대: waiting=B wants=S  /  blocked_by=A holds=X
--
-- STEP A3 에서는 이 목록에 B 가 아예 없었다. 락을 요청하지 않았기 때문이다.


-- ─────────────────────────────────────────────────────────────────────
-- [STEP A6] ▶ A  —  출금 확정
-- ─────────────────────────────────────────────────────────────────────
COMMIT;
-- 기대 (B 화면): 대기가 풀리며
-- | for_share |
-- | 300000.00 |    ← 확정된 새 잔액


-- ─────────────────────────────────────────────────────────────────────
-- [STEP A7] ▶ B  —  정리 후 다시 일반 조회
-- ─────────────────────────────────────────────────────────────────────
ROLLBACK;
SELECT balance_amt AS plain_select
  FROM acct
 WHERE acct_no = '10288000000001';
-- 기대:
-- | plain_select |
-- |    300000.00 |    ← 커밋됐으니 이제 새 값이 보인다


-- #####################################################################
-- PART B  —  (선택) 한 트랜잭션 안에서는 같은 값을 계속 본다
--
-- MySQL 기본 격리 수준(REPEATABLE READ)에서는 트랜잭션 안의 첫 SELECT 가
-- 그 시점의 "사진" 을 찍고, 이후 일반 SELECT 는 커밋 전까지 계속 그 사진을 본다.
-- 보고서를 뽑는 도중 숫자가 바뀌지 않도록 하기 위한 동작이다.
-- #####################################################################

-- ─────────────────────────────────────────────────────────────────────
-- [STEP B0] ▶ OBS
-- ─────────────────────────────────────────────────────────────────────
CALL lock_lab.reset();


-- ─────────────────────────────────────────────────────────────────────
-- [STEP B1] ▶ B  —  트랜잭션을 열고 조회
-- ─────────────────────────────────────────────────────────────────────
BEGIN;
SELECT balance_amt AS first_read FROM acct WHERE acct_no = '10288000000001';
-- 기대: 1000000.00  ← 이 순간이 B 의 "사진"


-- ─────────────────────────────────────────────────────────────────────
-- [STEP B2] ▶ A  —  출금하고 확정
-- ─────────────────────────────────────────────────────────────────────
BEGIN;
SELECT balance_amt INTO @bal FROM acct WHERE acct_no = '10288000000001' FOR UPDATE;
UPDATE acct SET balance_amt = balance_amt - 700000 WHERE acct_no = '10288000000001';
COMMIT;
-- 기대: Query OK  (B 는 락을 안 쥐었으니 A 는 기다리지 않는다)


-- ─────────────────────────────────────────────────────────────────────
-- [STEP B3] ▶ B  —  같은 트랜잭션에서 다시 조회
-- ─────────────────────────────────────────────────────────────────────
SELECT balance_amt AS second_read FROM acct WHERE acct_no = '10288000000001';
-- 기대: 1000000.00  ← A 가 커밋했는데도 여전히 100만
--
-- B 는 아직 자기 트랜잭션 안에 있고, 처음 찍은 사진을 계속 본다.


-- ─────────────────────────────────────────────────────────────────────
-- [STEP B4] ▶ B  —  트랜잭션을 끝내고 다시 조회
-- ─────────────────────────────────────────────────────────────────────
COMMIT;
SELECT balance_amt AS after_commit FROM acct WHERE acct_no = '10288000000001';
-- 기대: 300000.00  ← 새 트랜잭션이니 새 사진
--
-- 그래서 출금 판단에는 일반 SELECT 를 쓰면 안 된다.
-- 트랜잭션 안에서 낡은 사진을 보고 "잔액 충분" 이라고 판단할 수 있기 때문이다.
-- 판단용 조회는 FOR UPDATE 로 — 잠그면서 최신 확정값을 읽는다.
